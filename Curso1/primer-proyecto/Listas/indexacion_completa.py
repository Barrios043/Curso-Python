nombres = ["Maria", "Pedro", "Cipriano", "Roberto"]
print(nombres)

print(nombres[0]) #Output : Maria
print(nombres[1]) #Output : Pedro
print(nombres[2]) #Output : Cipriano
print(nombres[3]) #Output : Roberto

print(nombres[-1]) #Output : Roberto
print(nombres[-2]) #Output : Cipriano
print(nombres[-3]) #Output : Pedro
print(nombres[-4]) #Output : Maria

print(nombres[1:4]) #Output : ['Pedro', 'Cipriano', 'Roberto']
print(nombres[:2]) #Output :  ['Maria', 'Pedro']
print(nombres[2:]) #Output : ['Cipriano', 'Roberto']